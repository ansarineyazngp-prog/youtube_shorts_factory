# frozen_string_literal: true

require "net/http"
require "json"
require "uri"

module Shorts
  class TrendingTopicService
    CURATED_TOPICS = {
      "Psychology" => [
        "The Pratfall Effect: Why making mistakes makes you more likable",
        "The Spotlight Effect: Why nobody is actually looking at you",
        "The Bystander Effect: The dark truth about human hesitation",
        "3 Subtle Signs Someone Is Lying to You (FBI Technique)",
        "The Zeigarnik Effect: How your brain gets obsessed with unfinished tasks",
        "The Pygmalion Effect: How other people's expectations shape your reality"
      ],
      "Space & Science" => [
        "What happens if you fall into the Mariana Trench?",
        "Why the James Webb Telescope just shocked astronomers",
        "The Great Attractor: The mysterious gravitational monster pulling our galaxy",
        "What if Earth stopped spinning for just 5 seconds?",
        "The Boiling Lake of Dominica: Earth's natural death trap",
        "The WOW! Signal: Did deep space send us a message in 1977?"
      ],
      "History Mysteries" => [
        "The Library of Alexandria: What ancient knowledge was lost forever?",
        "The Dancing Plague of 1518: When an entire town danced to death",
        "The Voynich Manuscript: The book no codebreaker on Earth can read",
        "The Lost Roman Legion that disappeared without a trace in Scotland",
        "How a single pigeon saved 194 American soldiers in World War I"
      ],
      "Tech & AI" => [
        "Quantum Computers: Breaking modern encryption in 30 seconds",
        "Neuralink: How brain-computer interfaces will change human memory",
        "The Dead Internet Theory: Is 80% of the web generated by bots?",
        "Autonomous AI Swarms: The future of robotics that feels like Sci-Fi"
      ]
    }.freeze

    def self.fetch_trending_topic(category = nil)
      new(category).fetch
    end

    def initialize(category = nil)
      @category = category.presence || CURATED_TOPICS.keys.sample
    end

    def fetch
      if ENV["GEMINI_API_KEY"].present?
        fetch_from_gemini || fetch_from_curated
      elsif ENV["OPENAI_API_KEY"].present?
        fetch_from_openai || fetch_from_curated
      else
        fetch_from_curated
      end
    end

    private

    def fetch_from_curated
      existing_topics = ShortVideo.pluck(:topic).map(&:downcase)
      available = (CURATED_TOPICS[@category] || CURATED_TOPICS.values.flatten).reject do |t|
        existing_topics.include?(t.downcase)
      end

      topic = (available.any? ? available : CURATED_TOPICS.values.flatten).sample
      {
        topic: topic,
        category: @category,
        source: "curated_viral_vault"
      }
    end

    def fetch_from_gemini
      api_key = ENV["GEMINI_API_KEY"]
      url = URI("https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=#{api_key}")
      prompt = "Generate 1 viral YouTube Shorts hook topic in the #{@category} niche with high curiosity. Return ONLY the title text, under 60 characters, no quotes or prefix."

      req = Net::HTTP::Post.new(url, "Content-Type" => "application/json")
      req.body = {
        contents: [{ parts: [{ text: prompt }] }]
      }.to_json

      res = Net::HTTP.start(url.hostname, url.port, use_ssl: true, open_timeout: 5, read_timeout: 10) do |http|
        http.request(req)
      end

      if res.is_a?(Net::HTTPSuccess)
        data = JSON.parse(res.body)
        title = data.dig("candidates", 0, "content", "parts", 0, "text")&.strip
        if title.present?
          return {
            topic: title.gsub(/^["']|["']$/, "").strip,
            category: @category,
            source: "gemini_ai"
          }
        end
      end
      nil
    rescue StandardError => e
      Rails.logger.warn("Gemini topic fetch failed: #{e.message}")
      nil
    end

    def fetch_from_openai
      api_key = ENV["OPENAI_API_KEY"]
      url = URI("https://api.openai.com/v1/chat/completions")
      req = Net::HTTP::Post.new(url, {
        "Content-Type" => "application/json",
        "Authorization" => "Bearer #{api_key}"
      })
      req.body = {
        model: "gpt-4o-mini",
        messages: [
          { role: "system", content: "You generate viral high-retention YouTube Shorts topics. Return ONLY the topic string, no quotes." },
          { role: "user", content: "Give me 1 viral YouTube Shorts topic about #{@category}." }
        ],
        temperature: 0.8
      }.to_json

      res = Net::HTTP.start(url.hostname, url.port, use_ssl: true, open_timeout: 5, read_timeout: 10) do |http|
        http.request(req)
      end

      if res.is_a?(Net::HTTPSuccess)
        data = JSON.parse(res.body)
        title = data.dig("choices", 0, "message", "content")&.strip
        if title.present?
          return {
            topic: title.gsub(/^["']|["']$/, "").strip,
            category: @category,
            source: "openai"
          }
        end
      end
      nil
    rescue StandardError => e
      Rails.logger.warn("OpenAI topic fetch failed: #{e.message}")
      nil
    end
  end
end
